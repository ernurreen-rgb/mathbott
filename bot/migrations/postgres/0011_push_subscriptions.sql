-- Browser push subscriptions for the daily streak reminder (one row per device).
-- last_reminded_on is the UTC date of the last reminder, so a retried cron run
-- never sends the same device two reminders on one day.
CREATE TABLE push_subscriptions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE DEFERRABLE INITIALLY IMMEDIATE,
    endpoint TEXT NOT NULL UNIQUE,
    p256dh TEXT NOT NULL,
    auth TEXT NOT NULL,
    created_at TEXT DEFAULT to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'),
    last_reminded_on TEXT
);
CREATE INDEX idx_push_subscriptions_user ON push_subscriptions(user_id);
