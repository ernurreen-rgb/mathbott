-- Task collections from the task constructor (web /task-builder). A signed-in user ticks bank tasks,
-- puts them in order and downloads them as a PDF worksheet or a PPTX deck.
--
-- task_ids is that ordered list of bank_tasks ids. A bank task deleted later is left out when the
-- collection is read, and the next save drops it from the list.
-- header_text replaces the brand line at the top of the PDF.
-- title_image and background_image are the user's own PPTX backgrounds (the title slide and the
-- task slides), uploaded like task images and served from /api/images/<filename>.
CREATE TABLE task_collections (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE DEFERRABLE INITIALLY IMMEDIATE,
    title TEXT NOT NULL CHECK (char_length(title) BETWEEN 1 AND 120),
    header_text TEXT NOT NULL DEFAULT '' CHECK (char_length(header_text) <= 120),
    task_ids JSONB NOT NULL DEFAULT '[]'::jsonb
        CHECK (jsonb_typeof(task_ids) = 'array' AND jsonb_array_length(task_ids) <= 100),
    title_image TEXT,
    background_image TEXT,
    created_at TEXT NOT NULL DEFAULT to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'),
    updated_at TEXT NOT NULL DEFAULT to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')
);

CREATE INDEX idx_task_collections_user ON task_collections (user_id, updated_at DESC, id DESC);
