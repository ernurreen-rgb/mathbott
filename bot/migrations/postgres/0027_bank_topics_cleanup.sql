INSERT INTO bank_task_topic_map (bank_task_id, topic_id)
SELECT DISTINCT m.bank_task_id, fb.id
FROM umbrellas AS u
JOIN bank_topics AS old_t ON old_t.name_norm = u.old_norm
JOIN bank_task_topic_map AS m ON m.topic_id = old_t.id
JOIN bank_topics AS fb ON fb.name_norm = u.fallback_norm
WHERE NOT EXISTS (
    SELECT 1
    FROM bank_task_topic_map AS other_m
    JOIN bank_topics AS other_t ON other_t.id = other_m.topic_id
    WHERE other_m.bank_task_id = m.bank_task_id
      AND other_t.name_norm NOT IN (
          'алгебра', 'геометрия', 'тексеру_ұбт_2026',
          'математикалық талдау', 'өрнекті ықшамдау', 'алгебралық өрнектер',
          'бүтін шешімдер', 'теңдеу түбірлері', 'аралықтар', 'бұрыш'
      )
)
ON CONFLICT DO NOTHING;

