INSERT INTO bank_task_topic_map (bank_task_id, topic_id)
SELECT DISTINCT m.bank_task_id, tgt.id
FROM merges AS mg
JOIN bank_topics AS old_t ON old_t.name_norm = mg.old_norm
JOIN bank_task_topic_map AS m ON m.topic_id = old_t.id
JOIN bank_topics AS tgt ON tgt.name_norm = mg.target_norm
ON CONFLICT DO NOTHING;

