-- What a student's device can do when the streak reminder is offered on the mini-lesson summary,
-- and what the student chooses. device_state is the browser side's ReminderState (web/lib/push-reminders.ts).
CREATE TABLE reminder_prompt_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE DEFERRABLE INITIALLY IMMEDIATE,
    device_state TEXT NOT NULL CHECK (device_state IN ('unsupported', 'install', 'denied', 'off', 'on')),
    action TEXT NOT NULL CHECK (action IN ('seen', 'offered', 'enabled', 'snoozed', 'failed')),
    created_at TEXT NOT NULL DEFAULT to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')
);

CREATE INDEX idx_reminder_prompt_events_time ON reminder_prompt_events (created_at);
