CREATE TABLE bank_task_twins (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_bank_task_id BIGINT NOT NULL REFERENCES bank_tasks(id) ON DELETE CASCADE DEFERRABLE INITIALLY IMMEDIATE,
    twin_bank_task_id BIGINT NOT NULL UNIQUE REFERENCES bank_tasks(id) ON DELETE CASCADE DEFERRABLE INITIALLY IMMEDIATE,
    status TEXT NOT NULL DEFAULT 'approved' CHECK(status IN ('draft', 'approved')),
    origin TEXT NOT NULL DEFAULT 'manual' CHECK(origin IN ('manual', 'ai')),
    sort_order BIGINT NOT NULL DEFAULT 0,
    created_by BIGINT REFERENCES users(id) ON DELETE SET NULL DEFERRABLE INITIALLY IMMEDIATE,
    created_at TEXT DEFAULT to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'),
    CHECK(source_bank_task_id <> twin_bank_task_id)
);
CREATE INDEX idx_bank_task_twins_source ON bank_task_twins(source_bank_task_id, status, sort_order, id);
CREATE TABLE module_review_attempts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE DEFERRABLE INITIALLY IMMEDIATE,
    task_id BIGINT NOT NULL REFERENCES tasks(id) ON DELETE CASCADE DEFERRABLE INITIALLY IMMEDIATE,
    bank_task_id BIGINT NOT NULL REFERENCES bank_tasks(id) ON DELETE CASCADE DEFERRABLE INITIALLY IMMEDIATE,
    answer TEXT NOT NULL,
    is_correct SMALLINT NOT NULL DEFAULT 0,
    created_at TEXT DEFAULT to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')
);
CREATE INDEX idx_module_review_attempts_user_task ON module_review_attempts(user_id, task_id, id);
CREATE INDEX idx_solutions_user_task_id ON solutions(user_id, task_id, id);
