-- Separate problem origin/source metadata (e.g., Рустюмова, ҰБТ есебі) from subject topics.
-- Active tasks holding 'Рустюмова' or 'ҰБТ есебі' in bank_topics are migrated into bank_sources;
-- soft-deleted tasks in trash are intentionally left untouched.

CREATE TABLE bank_sources (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    name_norm TEXT NOT NULL UNIQUE
);

CREATE INDEX idx_bank_sources_name_norm ON bank_sources (name_norm);

CREATE TABLE bank_task_source_map (
    bank_task_id BIGINT NOT NULL REFERENCES bank_tasks(id) ON DELETE CASCADE DEFERRABLE INITIALLY IMMEDIATE,
    source_id BIGINT NOT NULL REFERENCES bank_sources(id) ON DELETE CASCADE DEFERRABLE INITIALLY IMMEDIATE,
    UNIQUE (bank_task_id, source_id)
);

CREATE INDEX idx_bank_task_source_map_source_task ON bank_task_source_map (source_id, bank_task_id);

INSERT INTO bank_sources (name, name_norm)
VALUES
    ('Рустюмова', 'рустюмова'),
    ('ҰБТ есебі', 'ұбт есебі')
ON CONFLICT (name_norm) DO NOTHING;

INSERT INTO bank_task_source_map (bank_task_id, source_id)
SELECT DISTINCT m.bank_task_id, s.id
FROM bank_task_topic_map m
JOIN bank_topics t ON t.id = m.topic_id
JOIN bank_tasks bt ON bt.id = m.bank_task_id
JOIN bank_sources s ON s.name_norm = t.name_norm
WHERE bt.deleted_at IS NULL
  AND t.name_norm IN ('рустюмова', 'ұбт есебі')
ON CONFLICT DO NOTHING;

DELETE FROM bank_task_topic_map m
USING bank_topics t, bank_tasks bt
WHERE m.topic_id = t.id
  AND bt.id = m.bank_task_id
  AND bt.deleted_at IS NULL
  AND t.name_norm IN ('рустюмова', 'ұбт есебі');

DELETE FROM bank_topics
WHERE id NOT IN (SELECT DISTINCT topic_id FROM bank_task_topic_map);
