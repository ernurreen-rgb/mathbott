-- How long API requests take as a student's device sees them: the slow ones (3 s or more), the
-- ones that failed, and a 10% sample of the rest for a baseline. The server only sees its own
-- part of a request; these rows show the whole trip (web/lib/request-timing.ts).
--
-- duration_ms is the device's time to the response; proxy_ms, api_ms and app_ms come from the
-- Server-Timing header: the time spent in the site's proxy function, the proxy's call to the API,
-- and the API's own handling. What the device waited beyond proxy_ms is its network.
-- details holds the rest: connection phases, network type, cold starts, browser.
CREATE TABLE client_request_timings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT REFERENCES users(id) ON DELETE CASCADE DEFERRABLE INITIALLY IMMEDIATE,
    tab_id TEXT NOT NULL,
    kind TEXT NOT NULL CHECK (kind IN ('slow', 'failed', 'sample')),
    method TEXT NOT NULL,
    path TEXT NOT NULL,
    page TEXT NOT NULL,
    status INTEGER,
    error TEXT CHECK (error IS NULL OR error IN ('network', 'aborted')),
    duration_ms INTEGER NOT NULL,
    ttfb_ms INTEGER,
    proxy_ms INTEGER,
    api_ms INTEGER,
    app_ms INTEGER,
    was_hidden INTEGER NOT NULL DEFAULT 0 CHECK (was_hidden IN (0, 1)),
    effective_type TEXT,
    started_at TEXT,
    details JSONB NOT NULL DEFAULT '{}'::jsonb,
    received_at TEXT NOT NULL DEFAULT to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')
);

CREATE INDEX idx_client_request_timings_received ON client_request_timings (received_at);
