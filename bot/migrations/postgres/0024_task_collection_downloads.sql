-- Download events from the task constructor (/task-builder): each PDF worksheet or PPTX deck
-- export records the format, whether an answer key was included, and how many tasks were exported.
-- If the collection is later deleted, collection_id becomes NULL so historical download counts stay accurate.
CREATE TABLE task_collection_downloads (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    collection_id BIGINT REFERENCES task_collections(id) ON DELETE SET NULL DEFERRABLE INITIALLY IMMEDIATE,
    collection_title TEXT NOT NULL DEFAULT '' CHECK (char_length(collection_title) <= 120),
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE DEFERRABLE INITIALLY IMMEDIATE,
    format TEXT NOT NULL CHECK (format IN ('pdf', 'pptx')),
    include_answers SMALLINT NOT NULL DEFAULT 1 CHECK (include_answers IN (0, 1)),
    task_count SMALLINT NOT NULL DEFAULT 0 CHECK (task_count >= 0),
    created_at TEXT NOT NULL DEFAULT to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')
);

CREATE INDEX idx_task_collection_downloads_created ON task_collection_downloads (created_at DESC, id DESC);
CREATE INDEX idx_task_collection_downloads_user ON task_collection_downloads (user_id, created_at DESC);
CREATE INDEX idx_task_collection_downloads_collection ON task_collection_downloads (collection_id);
