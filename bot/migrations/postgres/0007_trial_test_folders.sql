CREATE TABLE trial_test_folders (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parent_id INTEGER REFERENCES trial_test_folders(id) ON DELETE RESTRICT DEFERRABLE INITIALLY IMMEDIATE,
    name TEXT NOT NULL CHECK(length(trim(name)) BETWEEN 1 AND 120),
    sort_order INTEGER NOT NULL DEFAULT 0,
    CHECK(parent_id IS NULL OR parent_id <> id)
);
CREATE UNIQUE INDEX uq_trial_folder_root ON trial_test_folders(name) WHERE parent_id IS NULL;
CREATE UNIQUE INDEX uq_trial_folder_child ON trial_test_folders(parent_id, name) WHERE parent_id IS NOT NULL;
ALTER TABLE trial_tests ADD COLUMN folder_id INTEGER REFERENCES trial_test_folders(id) ON DELETE RESTRICT DEFERRABLE INITIALLY IMMEDIATE;
CREATE INDEX idx_trial_tests_folder ON trial_tests(folder_id);
INSERT INTO trial_test_folders (name, sort_order)
SELECT COALESCE(NULLIF(TRIM(category), ''), 'Жалпы'), MIN(COALESCE(sort_order, 0))
FROM trial_tests GROUP BY COALESCE(NULLIF(TRIM(category), ''), 'Жалпы');
UPDATE trial_tests SET category = COALESCE(NULLIF(TRIM(category), ''), 'Жалпы'),
    folder_id = (SELECT id FROM trial_test_folders
        WHERE name = COALESCE(NULLIF(TRIM(trial_tests.category), ''), 'Жалпы') AND parent_id IS NULL);
