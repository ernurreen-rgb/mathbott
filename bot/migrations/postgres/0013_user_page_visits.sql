-- Track lightweight student page visits and last seen path for admin diagnostics.
ALTER TABLE users ADD COLUMN last_seen_path TEXT;

CREATE TABLE user_page_visits (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE DEFERRABLE INITIALLY IMMEDIATE,
    path TEXT NOT NULL,
    visited_at TEXT NOT NULL DEFAULT to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')
);

CREATE INDEX idx_user_page_visits_user_time ON user_page_visits (user_id, visited_at DESC, id DESC);
