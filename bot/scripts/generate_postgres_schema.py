"""Regenerate the initial PostgreSQL schema from an isolated migrated SQLite DB.

Developer utility; never opens or changes the application's database.
Run from bot/: python scripts/generate_postgres_schema.py
"""
from pathlib import Path
from contextlib import closing
import gc
import re
import sqlite3
import sys
import tempfile

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from sqlalchemy import BigInteger, Boolean, Date, DateTime, Double, Float, Identity, Integer, MetaData, SmallInteger, Text, create_engine, text
from sqlalchemy.dialects import postgresql
from sqlalchemy.schema import AddConstraint, CreateIndex, CreateTable
from migrations.runner import run_migrations


def generate():
    with tempfile.TemporaryDirectory(prefix="mathbot-schema-") as directory:
        path = Path(directory) / "schema.db"
        run_migrations(str(path))
        with closing(sqlite3.connect(path)) as connection:
            definitions = dict(connection.execute("SELECT name, sql FROM sqlite_master WHERE type='table'"))
        engine = create_engine(f"sqlite:///{path.as_posix()}")
        metadata = MetaData()
        metadata.reflect(engine)
        engine.dispose()
        metadata.remove(metadata.tables["alembic_version"])
        dialect = postgresql.dialect()
        statements = ["-- PostgreSQL baseline equivalent to SQLite revision 0009_trial_test_retakes.\n"
                      "-- Generated by scripts/generate_postgres_schema.py; data is imported separately."]
        for table in metadata.tables.values():
            for column in table.columns:
                if isinstance(column.type, Boolean):
                    column.type = SmallInteger()
                elif isinstance(column.type, Integer):
                    column.type = BigInteger()
                elif isinstance(column.type, Float):
                    # SQLite REAL is 64-bit; PostgreSQL REAL is only 32-bit.
                    # Epoch clocks would otherwise lose whole minutes.
                    column.type = Double()
                elif isinstance(column.type, (DateTime, Date)):
                    # Preserve the existing UTC ISO string contract and JSON payloads.
                    column.type = Text()
                if column.server_default is not None and "CURRENT_TIMESTAMP" in str(column.server_default.arg).upper():
                    column.server_default.arg = text("to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')")
                if column.name == "id" and column.primary_key and re.search(r"\bid\s+INTEGER\s+PRIMARY\s+KEY\s+AUTOINCREMENT", definitions[table.name], re.I):
                    column.nullable = False
                    column.identity = Identity(always=False)
                    column.server_default = column.identity
            statements.append(str(CreateTable(table, include_foreign_key_constraints=[]).compile(dialect=dialect)).strip() + ";")
        for table in metadata.tables.values():
            for index in sorted(table.indexes, key=lambda item: item.name):
                where = index.dialect_options["sqlite"].get("where")
                if where is not None:
                    index.dialect_options["postgresql"]["where"] = where
                statements.append(str(CreateIndex(index).compile(dialect=dialect)).strip() + ";")
            for constraint in sorted(table.foreign_key_constraints, key=lambda item: tuple(column.name for column in item.columns)):
                columns = "_".join(column.name for column in constraint.columns)
                constraint.name = f"fk_{table.name}_{columns}"[:63]
                constraint.deferrable = True
                constraint.initially = "IMMEDIATE"
                statements.append(str(AddConstraint(constraint).compile(dialect=dialect)).strip() + ";")
        destination = Path(__file__).resolve().parents[1] / "migrations" / "postgres" / "0001_initial.sql"
        destination.parent.mkdir(parents=True, exist_ok=True)
        destination.write_text("\n\n".join(statements) + "\n", encoding="utf-8")
        print(f"Generated {len(metadata.tables)} tables in {destination.name}")
        gc.collect()


if __name__ == "__main__":
    generate()
