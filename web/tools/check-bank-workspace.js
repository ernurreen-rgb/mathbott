// Run with playwright-cli after tools/preview-bank-browser.js. All writes target
// the disposable fixture, not production. Starts on the library after setup.
async (page) => {
  const passed = [];
  const check = (condition, message) => { if (!condition) throw new Error(message); passed.push(message); };
  const rows = (count) => page.waitForFunction((expected) => document.querySelectorAll('[data-testid="bank-task-row"]').length === expected, count);
  await page.getByRole("searchbox", { name: "Банктен есеп іздеу", exact: true }).fill("#125");
  await rows(1);
  await page.getByRole("checkbox", { name: "PDF үшін банк №125 есебін таңдау", exact: true }).check();
  await page.getByRole("button", { name: "Банк №125 есебін ашу", exact: true }).click();
  await page.getByRole("button", { name: "Есепті өңдеу", exact: true }).waitFor();
  await page.getByRole("button", { name: "Өңдеу", exact: true }).click();
  const initialTask = await (await page.request.get("http://127.0.0.1:8100/api/admin/bank/tasks/125?email=bank-preview%40example.test")).json();
  const changedDifficulty = initialTask.difficulty === "C" ? "B" : "C";
  await page.getByLabel("Есептің күрделілігі").selectOption(changedDifficulty);
  await page.getByRole("button", { name: "Оқушы көрінісі", exact: true }).click();
  await page.getByRole("button", { name: "Өңдеу", exact: true }).click();
  check(await page.getByLabel("Есептің күрделілігі").inputValue() === changedDifficulty, "Unsaved edit survives student-preview switch");
  const saving = page.waitForResponse((response) => response.url().includes("/admin/bank/tasks/125") && response.request().method() === "PUT");
  await page.getByRole("button", { name: "Сақтау", exact: true }).click();
  check((await saving).ok(), "Task save reaches the real isolated API");
  await page.getByRole("button", { name: "Есепті өңдеу", exact: true }).waitFor();
  check((await page.getByRole("heading", { name: "Банк №125", exact: true }).locator("..").innerText()).includes(`v${initialTask.current_version + 1}`), "Successful save shows the new version without leaving the task");
  await page.getByText("Әрекеттер", { exact: true }).click();
  await page.getByRole("button", { name: "Тарих", exact: true }).click();
  await page.getByRole("button", { name: "Нұсқа көрінісі", exact: true }).first().waitFor();
  check(await page.getByRole("button", { name: "Нұсқа көрінісі", exact: true }).count() >= 2, "Version history preserves both snapshots");
  await page.getByRole("button", { name: "Жабу", exact: true }).click();
  await page.getByRole("button", { name: "Есептер тізіміне", exact: true }).click();
  await rows(1);
  check(await page.getByRole("searchbox", { name: "Банктен есеп іздеу", exact: true }).inputValue() === "#125", "Search is restored on return to the library");
  check(await page.getByRole("checkbox", { name: "PDF үшін банк №125 есебін таңдау", exact: true }).isChecked(), "Worksheet selection survives view, edit and save");
  await page.getByRole("button", { name: "Сүзгіні сақтау", exact: true }).click();
  await page.getByRole("textbox", { name: "Сүзгі атауы", exact: true }).fill("Тексеру: есеп 125");
  await page.getByRole("dialog").getByRole("button", { name: "Сақтау", exact: true }).click();
  await page.getByRole("button", { name: "Тазалау", exact: true }).click();
  await rows(50);
  const catalogToggle = page.getByRole("button", { name: "Каталог және тақырыптар", exact: true });
  if (await catalogToggle.isVisible()) await catalogToggle.click();
  await page.getByRole("button", { name: "Тексеру: есеп 125", exact: true }).click();
  await rows(1);
  check(await page.getByRole("searchbox", { name: "Банктен есеп іздеу", exact: true }).inputValue() === "#125", "Named saved filters restore their query");
  await page.getByRole("button", { name: "Тазалау", exact: true }).click();
  await rows(50);
  await page.getByRole("button", { name: "Келесі бет", exact: true }).click();
  await page.getByRole("checkbox", { name: "PDF үшін банк №75 есебін таңдау", exact: true }).waitFor();
  await page.getByRole("checkbox", { name: "PDF үшін банк №75 есебін таңдау", exact: true }).check();
  await page.getByRole("button", { name: "PDF дайындау", exact: true }).click();
  await page.getByRole("heading", { name: "PDF жинағын дайындау", exact: true }).waitFor();
  check(await page.getByRole("list", { name: "PDF есептерінің реті", exact: true }).getByRole("listitem").count() === 2, "PDF collection includes selections from two server pages");
  const downloadEvent = page.waitForEvent("download", { timeout: 60000 });
  await page.getByRole("button", { name: "PDF жүктеу", exact: true }).click();
  const download = await downloadEvent;
  await download.saveAs("output/playwright/bank-workspace.pdf");
  check((await download.failure()) === null, "PDF download completes with real MathLive formulas");
  await page.getByRole("button", { name: "Алдыңғы бет", exact: true }).click();
  await page.getByRole("button", { name: "Банк №125 есебін ашу", exact: true }).waitFor();
  await page.getByRole("button", { name: "Банк №125 есебін ашу", exact: true }).click();
  await page.getByRole("button", { name: "Есепті өңдеу", exact: true }).waitFor();
  await page.getByRole("button", { name: "Өңдеу", exact: true }).click();
  await page.getByLabel("Есептің күрделілігі").selectOption("A");
  const taskResponse = await page.request.get("http://127.0.0.1:8100/api/admin/bank/tasks/125?email=bank-preview%40example.test");
  const task = await taskResponse.json();
  const concurrentDifficulty = changedDifficulty === "B" ? "C" : "B";
  const concurrent = await page.request.put("http://127.0.0.1:8100/api/admin/bank/tasks/125", { multipart: {
    email: "bank-preview@example.test", difficulty: concurrentDifficulty, expected_current_version: String(task.current_version), dedup_confirmed: "true",
  } });
  check(concurrent.ok(), "Concurrent edit is committed in the disposable fixture");
  await page.getByRole("button", { name: "Сақтау", exact: true }).click();
  await page.getByRole("button", { name: "Жаңа нұсқаны жүктеу", exact: true }).waitFor();
  check(await page.getByRole("button", { name: "Сақтау", exact: true }).isDisabled(), "Version conflicts block overwriting newer content");
  await page.getByRole("button", { name: "Жаңа нұсқаны жүктеу", exact: true }).click();
  await page.getByRole("button", { name: "Сақтау", exact: true }).waitFor({ state: "visible" });
  await page.waitForFunction((difficulty) => document.querySelector('select[aria-label="Есептің күрделілігі"]')?.value === difficulty, concurrentDifficulty);
  check(await page.getByLabel("Есептің күрделілігі").inputValue() === concurrentDifficulty, "Conflict reload fetches and displays the current version");
  await page.getByRole("button", { name: "Бас тарту", exact: true }).click();
  await page.reload();
  await page.getByRole("button", { name: "Есепті өңдеу", exact: true }).waitFor();
  check(await page.getByRole("heading", { name: "Банк №125", exact: true }).isVisible(), "Task deep links survive a full reload");
  return { passed, total: passed.length, url: page.url() };
}
